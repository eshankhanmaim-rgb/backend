#!/usr/bin/env python3
"""
Generate an Ed25519 key pair for the Pruvate Auth Platform.

Usage:
    python scripts/gen_keys.py

Output:
    - Private key (base64) → paste into .env as ED25519_PRIVATE_KEY_B64
    - Public key (base64)  → paste into .env as ED25519_PUBLIC_KEY_B64
    - Public key as a C++ byte array → paste into loader/auth.cpp
"""
from __future__ import annotations
import base64
import sys


def main():
    try:
        from nacl.signing import SigningKey
    except ImportError:
        print("ERROR: PyNaCl not installed. Run: pip install pynacl", file=sys.stderr)
        sys.exit(1)

    # Generate a fresh Ed25519 signing key
    sk = SigningKey.generate()
    vk = sk.verify_key

    # Raw bytes
    private_seed = bytes(sk)       # 32-byte seed
    public_key = bytes(vk)         # 32-byte public key

    # libsodium "extended" format: seed || public key (64 bytes total)
    # This matches what libsodium's crypto_sign_keypair stores
    private_extended = private_seed + public_key  # 64 bytes

    private_b64 = base64.b64encode(private_extended).decode()
    public_b64 = base64.b64encode(public_key).decode()

    # Format public key as C++ byte array
    cpp_array = ", ".join(f"0x{b:02x}" for b in public_key)

    print("=" * 70)
    print("Ed25519 Key Pair — Generated by gen_keys.py")
    print("=" * 70)
    print()
    print("--- .env (server configuration) ---")
    print()
    print("# KEEP THIS PRIVATE. NEVER COMMIT TO SOURCE CONTROL.")
    print(f"ED25519_PRIVATE_KEY_B64={private_b64}")
    print()
    print("# This is the public key. Safe to embed in the C++ binary.")
    print(f"ED25519_PUBLIC_KEY_B64={public_b64}")
    print()
    print("--- loader/auth.cpp (paste inside the binary) ---")
    print()
    print("// Ed25519 public key — embedded in the loader binary")
    print("// Generated by backend/scripts/gen_keys.py")
    print("// Replace this when rotating keys. See SETUP.md for the rotation procedure.")
    print("static const uint8_t ED25519_PUBLIC_KEY[32] = {")
    print(f"    {cpp_array}")
    print("};")
    print()
    print("=" * 70)
    print("SECURITY NOTES:")
    print("  1. Store ED25519_PRIVATE_KEY_B64 only in your .env / secrets manager.")
    print("  2. The public key (ED25519_PUBLIC_KEY_B64 and the C++ array) is NOT secret.")
    print("  3. When rotating keys:")
    print("     a. Generate a new pair with this script.")
    print("     b. Update the server .env immediately.")
    print("     c. Rebuild and redistribute the loader binary with the new public key.")
    print("     d. Old loaders will still work until you update LOADER_MIN_VERSION")
    print("        in settings to force an update.")
    print("=" * 70)


if __name__ == "__main__":
    main()
